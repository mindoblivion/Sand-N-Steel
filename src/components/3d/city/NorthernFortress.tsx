import React, { useMemo, useEffect } from 'react';
import { useGLTF } from '@react-three/drei';
import * as THREE from 'three';
import { SkeletonUtils } from 'three-stdlib';

/**
 * NorthernFortress.tsx — Roman fortress landmark north of the Colosseum.
 *
 * Loads the normals-corrected GLB asset
 * (public/_workspace_roman_fortress_normals_candidate.glb) through the
 * existing useGLTF pipeline. The original GLB (trimesh-generated) had no
 * NORMAL attributes on any mesh, causing invisible rendering on SwiftShader.
 * The candidate was produced by glTF Transform 4.5.1 with generated normals
 * and preserves all geometry, materials, indices, and node transforms.
 *
 * The model uses Z-up coordinates (generated by trimesh).  The Z-up → Y-up
 * conversion (a -90° rotation about X) is already baked into every GLB node
 * matrix, so this component applies NO rotation of its own — the outer group
 * is a pure position/scale transform.  (An earlier revision also applied
 * [-π/2, 0, 0] on the outer group, duplicating the baked-in conversion and
 * rendering the fortress a further 90° past vertical.)
 *
 * Model dimensions (accessor bounding boxes, before the node rotation):
 *   Fortress_Stone  X±35  Y±35  Z 0–26.4   (70×70 ground footprint)
 *   Gates_Wood     X±2.25 Y≈-28.5 Z 0.05–3.95 (south gate, 4.5 wide)
 *
 * At scale 0.30 the footprint becomes 21×21 world units, height ~7.92.
 * Position [0, 4.72, -71.5] places it on the motte's flat summit (summit
 * height Y=4.72, summit radius ≈15.73, fortress half-width 10.5 — corners
 * at radius 14.85, clearance 0.88 from the summit edge).
 *
 * World-space bounds after the node rotation combined with this group's
 * position/scale:
 *   X: [-10.5, 10.5]   Y: [4.72, 12.64]   Z: [-82.0, -61.0]
 *   Gate (model Y=-28.5) → world Z ≈ -62.95 (south side, facing city +Z)
 *
 * Collision is handled by rect colliders in collisionShapes.ts (fortress-*
 * IDs) with a 2.0-unit gap at the gate for player passage.  The visual gate
 * is 1.35 units wide at this scale; collision is intentionally more forgiving.
 */

const FORTRESS_URL = '/_workspace_roman_fortress_normals_candidate.glb';

// Preload at module import time (same pattern as GladiatorMesh).
try {
  useGLTF.preload(FORTRESS_URL);
} catch {
  // Silent fallback — useGLTF will load on demand if preload fails.
}

const FortressModel: React.FC = () => {
  const gltf = useGLTF(FORTRESS_URL);

  // Clone so the cached scene is never mutated across instances.
  const cloned = useMemo(() => SkeletonUtils.clone(gltf.scene), [gltf.scene]);

  useEffect(() => {
    cloned.traverse((child) => {
      if ((child as THREE.Mesh).isMesh) {
        child.castShadow = true;
        child.receiveShadow = true;
      }
    });
  }, [cloned]);

  return <primitive object={cloned} />;
};

/**
 * Error boundary wrapper — a load failure renders nothing rather than
 * crashing the city hub, consistent with ThreeComponentErrorBoundary usage
 * in CityHubScene.
 */
class FortressErrorBoundary extends React.Component<
  { children: React.ReactNode },
  { hasError: boolean }
> {
  constructor(props: { children: React.ReactNode }) {
    super(props);
    this.state = { hasError: false };
  }
  static getDerivedStateFromError() {
    return { hasError: true };
  }
  componentDidCatch(err: unknown) {
    console.warn('[NorthernFortress] GLB failed to load:', err);
  }
  render() {
    if (this.state.hasError) return null;
    return this.props.children;
  }
}

export const NorthernFortress: React.FC = () => {
  return (
    <FortressErrorBoundary>
      <React.Suspense fallback={null}>
        <group position={[0, 4.72, -71.5]} scale={0.30}>
          <FortressModel />
        </group>
      </React.Suspense>
    </FortressErrorBoundary>
  );
};
